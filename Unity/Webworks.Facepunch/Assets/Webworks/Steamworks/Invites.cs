using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using Webworks.Internal;

namespace Steamworks
{
	public static partial class SteamMatchmaking
	{
		internal static void CheckForPendingInvite()
		{
			var token = PendingInviteToken();
			if (string.IsNullOrEmpty(token)) return;
			ResolvePendingInviteAsync(token).Forget("CheckForPendingInvite");
		}

		public static async Task<bool> ResolvePendingInviteAsync(string inviteToken)
		{
			if (string.IsNullOrEmpty(inviteToken)) return false;

			Dictionary<string, object> d;
			try
			{
				d = WebworksJson.Obj(await ApiClient.GetAsync("/Matchmaking/ResolveInvite?token=" + Uri.EscapeDataString(inviteToken)));
			}
			catch (Exception ex)
			{
				UnityEngine.Debug.LogWarning("[Webworks] invite link resolve failed: " + ex.Message);
				return false;
			}

			ulong lobbyId = WebworksJson.Ulong(d, "lobbyId");
			if (lobbyId == 0)
			{
				UnityEngine.Debug.LogWarning("[Webworks] invite link is expired or invalid");
				return false;
			}

			SteamFriends.RaiseGameLobbyJoinRequested(new Data.Lobby { Id = lobbyId }, (SteamId)0);
			return true;
		}

		static string PendingInviteToken()
		{
#if UNITY_WEBGL && !UNITY_EDITOR
			try
			{
				// Current param first, then the pre-rename Weeam/Webeam spelling, so an invite link
				// generated by an older deployment still auto-joins instead of silently doing nothing.
				var token = WebworksNative.Webworks_QueryParam("webworksInvite");
				if (string.IsNullOrEmpty(token)) token = WebworksNative.Webworks_QueryParam("webeamInvite");
				return token;
			}
			catch (Exception ex) { UnityEngine.Debug.LogWarning("[Webworks] could not read invite query param: " + ex.Message); return null; }
#else
			var args = Environment.GetCommandLineArgs();
			foreach (var a in args)
			{
				if (a.StartsWith("-webworksinvite=", StringComparison.OrdinalIgnoreCase))
					return a.Substring("-webworksinvite=".Length);
			}
			foreach (var a in args)
			{
				if (a.StartsWith("-webeaminvite=", StringComparison.OrdinalIgnoreCase))
					return a.Substring("-webeaminvite=".Length);
			}
			return null;
#endif
		}
	}
}
